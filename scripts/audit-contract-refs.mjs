#!/usr/bin/env node

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const SCAN_ROOTS = ['src', 'server', 'scripts', 'contracts'];
const SCAN_FILES = [
  'render.yaml',
  'Dockerfile.hermetic',
  'TODO.md',
  'playwright.config.js',
  'vite.config.ts',
];
const ENV_NAME_RE =
  /\b(?:VITE_[A-Z0-9_]*(?:ID|CONTRACT_ID)|[A-Z][A-Z0-9_]*(?:CONTRACT_ID|_VAULT_ID|_DAO_ID)|CONTRACT_ID)\b/g;
const STRKEY_RE = /\bC[A-Z2-7]{55}\b|\bCC325F[A-Z0-9]+\b/g;
const SKIP_DIRS = new Set(['node_modules', 'dist', 'coverage', '.git']);

function isEnvFile(name) {
  return name.startsWith('.env.');
}

function collectFiles(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) collectFiles(join(dir, entry.name), files);
    } else if (/\.(?:[cm]?[jt]sx?|json|ya?ml|sh|toml|md)$/.test(entry.name)) {
      files.push(join(dir, entry.name));
    }
  }
  return files;
}

const paths = new Set(SCAN_FILES.filter((file) => statSync(join(ROOT, file), { throwIfNoEntry: false })));
for (const root of SCAN_ROOTS) {
  paths.add(root);
}
for (const entry of readdirSync(ROOT, { withFileTypes: true })) {
  if (entry.isFile() && isEnvFile(entry.name)) paths.add(entry.name);
}

const files = [];
for (const path of paths) {
  const absolute = join(ROOT, path);
  if (statSync(absolute, { throwIfNoEntry: false })?.isDirectory()) {
    collectFiles(absolute, files);
  } else if (statSync(absolute, { throwIfNoEntry: false })?.isFile()) {
    files.push(absolute);
  }
}

function environmentFor(file, line) {
  const normalized = relative(ROOT, file).replaceAll('\\', '/');
  const source = `${normalized} ${line}`.toLowerCase();
  if (/mainnet/.test(source)) return 'mainnet';
  if (/testnet/.test(source)) return 'testnet';
  if (/\.env\./.test(normalized)) return 'environment file (network not specified)';
  return 'runtime/build default (network not specified)';
}

function defaultFor(line, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const assignment = new RegExp(
    `(?:${escaped})\\s*(?:=|:)\\s*(?:process\\.env\\.[A-Z0-9_]+\\s*\\|\\|\\s*)?(['"\`]?)([^\\s,;'"\`]+)`,
  ).exec(line);
  if (assignment) return assignment[2];
  const quoted = /(['"`])([^'"`]{1,120})\1/.exec(line);
  return quoted?.[2] ?? '—';
}

const rows = [];
for (const file of [...new Set(files)].sort()) {
  const lines = readFileSync(file, 'utf8').split(/\r?\n/);
  lines.forEach((line, index) => {
    const names = new Set();
    for (const match of line.matchAll(ENV_NAME_RE)) names.add(match[0]);
    for (const match of line.matchAll(STRKEY_RE)) names.add(`hardcoded strkey ${match[0]}`);
    for (const name of names) {
      const variableName = name.startsWith('hardcoded strkey ') ? 'hardcoded strkey' : name;
      const defaultValue = name.startsWith('hardcoded strkey ')
        ? name.slice('hardcoded strkey '.length)
        : defaultFor(line, name);
      rows.push({
        file: relative(ROOT, file).replaceAll('\\', '/'),
        line: index + 1,
        variableName,
        defaultValue,
        environment: environmentFor(file, line),
      });
    }
  });
}

console.log('# Contract ID Reference Inventory');
console.log('');
console.log('Generated by `node scripts/audit-contract-refs.mjs`. Each match records the source line, name, detected default, and likely environment.');
console.log('');
console.log('| File:line | Variable name | Default value | Environment |');
console.log('|---|---|---|---|');
for (const row of rows) {
  const escape = (value) => String(value).replaceAll('|', '\\|').replaceAll('`', '\\`');
  console.log(
    `| ${escape(`${row.file}:${row.line}`)} | ${escape(row.variableName)} | ${escape(row.defaultValue)} | ${escape(row.environment)} |`,
  );
}
